def _relevel(items: list[dict]) -> list[dict]:
    """Лёгкие — детям; бывшие лёгкие школьные → средние; бывшие средние → сложные; хардкор снимаем."""
    out = []
    for r in items:
        title = r["title"]
        old = r["level"]
        if title in KIDS_TITLES:
            r["level"] = "easy"
            out.append(r)
            continue
        if old == "hard":
            continue
        if old == "easy":
            r["level"] = "medium"
        elif old == "medium":
            r["level"] = "hard"
        out.append(r)
    return out


