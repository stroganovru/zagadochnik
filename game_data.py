def _fp(text: str) -> str:
    s = (text or "").lower().replace("ё", "е")
    s = re.sub(r"[^а-яa-z0-9]+", " ", s)
    return re.sub(r"\s+", " ", s).strip()[:100]


def _apply(it: dict) -> dict:
    title = (it.get("title") or "").strip()
    extra = CLARIFY.get(title) or {}
    text = extra.get("text") or it.get("text") or ""
    answer = extra.get("answer") or it.get("answer") or ""
    return {
        "title": title,
        "text": text.strip(),
        "answer": answer.strip(),
        "source": (it.get("source") or "").strip(),
        "level": it.get("level"),
    }


def _pack(items: list, level: str, start: int) -> list[dict]:
    out = []
    n = start
    seen_titles: set[str] = set()
    seen_fp: set[str] = set()
    for it in items:
        rec = _apply({**it, "level": level})
        if rec["title"] in DROP_TITLES or rec["title"] in seen_titles:
            continue
        if not rec["text"] or not rec["answer"]:
            continue
        fp = _fp(rec["text"])
        if fp in seen_fp:
            continue
        seen_titles.add(rec["title"])
        seen_fp.add(fp)
        out.append({"id": n, "level": level, **rec})
        n += 1
    return out


